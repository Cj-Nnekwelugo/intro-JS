// assignment operators

// addition assignment
let countValue = 10;
countValue += 15;
console.log(countValue); // Output: 25

// subtraction assignment
let anotherValue = 20;
anotherValue -= 5;
console.log(anotherValue); // Output: 15

// multiplication assignment
let productValue = 10;
productValue *= 5;
console.log(productValue); // Output: 50

// division assignment
let quotientValue = 20;
quotientValue /= 4;
console.log(quotientValue); // Output: 5

// modulus assignment
let remainderValue = 10;
remainderValue %= 3;
console.log(remainderValue); // Output: 1

// exponentiation assignment
let exponentValue = 2;
exponentValue **= 3;
console.log(exponentValue); // Output: 8


// logical operators

// not operator
console.log(!false); // Output: true
console.log(Boolean(5)); 

